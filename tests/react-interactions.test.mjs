import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { createServer } from 'vite';
import { createElement, act } from 'react';
import { createRoot } from 'react-dom/client';

const dom = new JSDOM('<!doctype html><html><body><div id="root"></div></body></html>', { url: 'http://localhost/', pretendToBeVisual: true });
const { window } = dom;
globalThis.window = window;
globalThis.document = window.document;
globalThis.MutationObserver = window.MutationObserver;
globalThis.requestAnimationFrame = window.requestAnimationFrame.bind(window);
globalThis.cancelAnimationFrame = window.cancelAnimationFrame.bind(window);
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
window.matchMedia = () => ({ matches: false, addEventListener() {}, removeEventListener() {} });
window.HTMLElement.prototype.getAnimations = () => [];
window.HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); this.querySelector('button')?.focus(); };
window.HTMLDialogElement.prototype.close = function () { this.removeAttribute('open'); this.dispatchEvent(new window.Event('close')); };
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' });
try {
  const { default: App } = await server.ssrLoadModule('/src/App.jsx');
  const root = createRoot(document.getElementById('root'));
  await act(async () => { root.render(createElement(App)); });
  const toggle = document.getElementById('mobile-toggle');
  assert.ok(document.querySelector('#work') && document.querySelector('#contact'));
  await act(async () => toggle.click());
  assert.equal(toggle.getAttribute('aria-expanded'), 'true');
  await act(async () => document.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true })));
  assert.equal(toggle.getAttribute('aria-expanded'), 'false');
  assert.equal(document.activeElement, toggle, 'Escape returns focus to the menu toggle');
  assert.equal(document.querySelectorAll('main').length, 1);
  assert.equal(document.querySelectorAll('main h1').length, 1);
  assert.match(document.querySelector('h1').textContent, /Fullstack/);
  assert.equal(document.querySelectorAll('[data-project-track] > li:not([data-project-marquee-clone])').length, 5);
  assert.equal(document.querySelector('[data-project-track]').tagName, 'UL');
  for (const image of document.querySelectorAll('img')) assert.ok(image.hasAttribute('alt'), 'Every image needs explicit alternative text');
  const heroPortrait = document.querySelector('#hero img');
  assert.equal(heroPortrait.getAttribute('loading'), 'eager', 'The above-the-fold portrait must not be lazy loaded');
  assert.equal(heroPortrait.getAttribute('fetchpriority'), 'high');
  for (const image of document.querySelectorAll('#hero img, #about [data-slide] img')) {
    assert.ok(image.getAttribute('srcset')?.includes('w'), 'Portraits provide width-based responsive sources');
    assert.ok(image.getAttribute('sizes'), 'Responsive sources declare their layout slots');
    assert.ok(Number(image.getAttribute('width')) > 0 && Number(image.getAttribute('height')) > 0);
  }
  heroPortrait.dispatchEvent(new window.Event('error'));
  assert.equal(heroPortrait.getAttribute('srcset'), null, 'An unavailable responsive source must not override the original-image fallback');
  assert.equal(heroPortrait.getAttribute('src'), 'image/chandung2remove.png');
  for (const link of document.querySelectorAll('a[href^="#"]')) assert.ok(document.getElementById(link.getAttribute('href').slice(1)), 'Internal links need a real target');
  const slider = document.querySelector('[data-autoplay-slider]');
  const next = slider.querySelector('[data-slide-next]');
  assert.equal(next.tagName, 'BUTTON', 'The portrait action uses native keyboard activation');
  assert.equal(next.type, 'button');
  assert.equal(slider.querySelector('[role="tablist"], [role="tab"]'), null, 'Photo buttons are not incomplete tabs');
  assert.equal(slider.querySelector('[data-dot-index="0"]').getAttribute('aria-pressed'), 'true');
  const slides = [...slider.querySelectorAll('[data-slide]')];
  const before = slides.map(slide => slide.className);
  await act(async () => slider.querySelector('[data-slide-next]').click());
  assert.notDeepEqual(slides.map(slide => slide.className), before);
  assert.equal(slider.querySelector('[data-dot-index="1"]').getAttribute('aria-pressed'), 'true');
  assert.equal(slides[0].getAttribute('aria-hidden'), 'true');
  next.focus();
  await act(async () => next.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true })));
  assert.equal(slider.querySelector('[data-dot-index="0"]').getAttribute('aria-pressed'), 'true');
  assert.equal(document.activeElement, next, 'Arrow navigation preserves focus');
  const caseButton = document.querySelector('[data-open-futurelearn]');
  caseButton.focus();
  await act(async () => caseButton.click());
  assert.equal(document.querySelector('dialog[open] #case-title').textContent, 'Học tập vui hơn cùng FutureLearn.');
  assert.equal(document.body.style.overflow, 'hidden');
  await act(async () => document.querySelector('.case-dialog__close').click());
  assert.equal(document.querySelector('dialog'), null);
  assert.equal(document.activeElement, caseButton);
  assert.equal(document.body.style.overflow, '');
  const clonedButton = document.querySelector('[data-project-marquee-clone] [data-open-futurelearn]');
  assert.ok(clonedButton);
  await act(async () => clonedButton.click());
  assert.ok(document.querySelector('dialog[open]'));
  await act(async () => document.querySelector('dialog').click());
  assert.equal(document.querySelector('dialog'), null);
  const learnButton = document.querySelector('[data-open-learnspace]');
  learnButton.focus();
  await act(async () => learnButton.click());
  assert.match(document.querySelector('dialog[open] #learn-case-title').textContent, /LearnSpace/);
  assert.equal(document.body.style.overflow, 'hidden');
  assert.equal(document.querySelector('dialog a[href="https://learn-space.khanhht.tech"]').textContent.trim(), 'Xem dự án ↗');
  await act(async () => document.querySelector('.case-dialog__close').click());
  assert.equal(document.activeElement, learnButton);
  assert.equal(document.body.style.overflow, '');
  const clonedLearnButton = document.querySelector('[data-project-marquee-clone] [data-open-learnspace]');
  assert.ok(clonedLearnButton);
  await act(async () => clonedLearnButton.click());
  assert.ok(document.querySelector('dialog[open] #learn-case-title'));
  await act(async () => document.querySelector('dialog').click());
  assert.equal(document.activeElement, learnButton);
  console.log('React interactions, case study dialog and cloned project card checks passed.');
  await act(async () => root.unmount());
} finally {
  dom.window.close();
  await server.close();
}
